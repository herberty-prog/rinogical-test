/* 時差の計算：都市の経度（東経はプラス、西経はマイナス） */
const JISA_CITIES = [
  { n: "ロンドン", lon: 0 }, { n: "ニューヨーク", lon: -75 }, { n: "ロサンゼルス", lon: -120 },
  { n: "カイロ", lon: 30 }, { n: "ニューデリー", lon: 75 }, { n: "シドニー", lon: 150 }, { n: "ペキン", lon: 120 },
];
const hourStr = (h) => `${((h % 24) + 24) % 24}時`;
function genJisa() {
  const c = pickOne(JISA_CITIES), jp = rint(0, 23);
  const diff = (135 - c.lon) / 15, h = jp - diff;
  const ans = hourStr(h);
  const choices = choices4(ans, [hourStr(jp + diff), hourStr(h + 1), hourStr(h - 1), hourStr(h + 12)]);
  return { type: "text", ui: "choice", kind: "時差", text: true,
    q: `日本が${jp}時のとき、${c.n}（標準時子午線は${c.lon === 0 ? "経度0度" : c.lon > 0 ? `東経${c.lon}度` : `西経${-c.lon}度`}）は何時？（サマータイムは考えない）`,
    a: ans, choices, v: { t: "jisa", jp, lon: c.lon }, why: `経度の差は${Math.abs(135 - c.lon)}度。15度で1時間なので時差は${Math.abs(diff)}時間。日本より西（東経が小さい）なら時刻はおそい。` };
}
function genNihonProblem(level) {
  if (level >= 3 && Math.random() < 0.2) return genJisa();
  return genTableProblem(NIHON_DATA, level);
}

