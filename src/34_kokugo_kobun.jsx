/* Lv1-2 は仮名遣いの基本と竹取物語、Lv3 以降は古語の意味や長めの仮名遣いも混ぜる */
function genKobunProblem(level) {
  const pool = level >= 3 ? KOBUN_DATA : KOBUN_DATA.filter(d => !d.adv);
  const d = pool[rint(0, pool.length - 1)];
  const q = d.q || (d.kind === "仮名遣い"
    ? `歴史的仮名遣いの「${d.w}」を、今の仮名遣いに直すと？`
    : `古語「${d.w}」の意味はどれ？`);
  return { type: "text", ui: "choice", kind: d.kind, q, a: d.a, choices: shuffle([d.a].concat(d.ng)), mark: d.w || null, why: d.why };
}

