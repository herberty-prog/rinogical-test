/* 計算問題：密度（3つの聞き方）と質量パーセント濃度 */
const DENSITY_MAT = [{ n: "アルミニウム", d: 2.7 }, { n: "鉄", d: 7.9 }, { n: "銅", d: 8.9 }, { n: "鉛", d: 11.3 }];
const r1 = (x) => Math.round(x * 10) / 10;
function genBusshitsuCalc() {
  const t = rint(1, 3);
  if (t === 1) {
    const M = pickOne(DENSITY_MAT), V = rint(2, 10), m = r1(M.d * V);
    return { type: "number", ui: "choice", kind: "計算", text: true, q: `質量${m}g、体積${V}cm³の物質の密度は何g/cm³？`, a: M.d,
      choices: choices4(M.d, [r1(V / m), r1(M.d + 1), r1(M.d * 2), r1(M.d - 1)].filter(x => x > 0)), v: { t: "density", m, V },
      why: "密度＝質量÷体積。" };
  }
  if (t === 2) {
    const M = pickOne(DENSITY_MAT), V = rint(2, 10), m = r1(M.d * V);
    return { type: "number", ui: "choice", kind: "計算", text: true, q: `${M.n}（密度${M.d}g/cm³）${V}cm³の質量は何g？`, a: m,
      choices: choices4(m, [r1(M.d + V), r1(m + M.d), r1(V / M.d), r1(m * 2)].filter(x => x > 0)), v: { t: "mass", d: M.d, V },
      why: "質量＝密度×体積。" };
  }
  const total = pickOne([50, 100, 200, 250]), pct = pickOne([4, 5, 10, 20, 25]), s = total * pct / 100, w = total - s;
  return { type: "number", ui: "choice", kind: "計算", text: true, q: `水${w}gに食塩${s}gをとかした。質量パーセント濃度は何%？`, a: pct,
    choices: choices4(pct, [r1(s / w * 100), pct * 2, pct + 5, Math.max(1, pct - 2)]), v: { t: "conc", s, w },
    why: "濃度(%)＝溶質÷（溶質＋溶媒）×100。水の質量だけで割らないこと。" };
}
function genBusshitsuProblem(level) {
  if (level >= 3 && Math.random() < 0.25) return genBusshitsuCalc();
  return genTableProblem(BUSSHITSU_DATA, level);
}

