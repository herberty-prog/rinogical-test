/* 計算問題：音の速さ（雷・やまびこ）、ばね、重さ */
function genHikariCalc() {
  const t = rint(1, 4);
  if (t === 1) {
    const sec = rint(2, 9), dist = 340 * sec;
    return { type: "number", ui: "choice", kind: "計算", text: true, q: `雷の光が見えてから${sec}秒後に音が聞こえた。雷までの距離は何m？（音の速さ340m/s）`, a: dist,
      choices: choices4(dist, [dist / 2, 340 + sec, dist + 340, dist - 340]), v: { t: "sound", s: 340, sec },
      why: "距離＝速さ×時間。" };
  }
  if (t === 2) {
    const sec = pickOne([2, 4, 6, 8, 10]), dist = 340 * sec / 2;
    return { type: "number", ui: "choice", kind: "計算", text: true, q: `山に向かってさけぶと、${sec}秒後にやまびこが聞こえた。山までの距離は何m？（音の速さ340m/s）`, a: dist,
      choices: choices4(dist, [dist * 2, dist + 340, dist - 170, 340 * sec + 340]), v: { t: "echo", s: 340, sec },
      why: "やまびこは山まで行って帰ってくる。往復の距離÷2。" };
  }
  if (t === 3) {
    const per = pickOne([2, 3, 4, 5]), F = rint(2, 6), x = per * F;
    return { type: "number", ui: "choice", kind: "計算", text: true, q: `1Nの力で${per}cmのびるばねを、${F}Nの力で引くと何cmのびる？`, a: x,
      choices: choices4(x, [per + F, x + per, x - per, F]), v: { t: "spring", per, F },
      why: "フックの法則：のびは力に比例。1Nで" + per + "cmなら、" + F + "Nでその" + F + "倍。" };
  }
  const g = pickOne([200, 300, 500, 600, 800, 1200]), N = g / 100;
  return { type: "number", ui: "choice", kind: "計算", text: true, q: `質量${g}gの物体にはたらく重力は約何N？（100gの物体にはたらく重力を1Nとする）`, a: N,
    choices: choices4(N, [g / 10, g, N * 2, N + 1]), v: { t: "weight", g },
    why: "100gで1Nなので、gを100で割る。" };
}
function genHikariProblem(level) {
  if (level >= 3 && Math.random() < 0.25) return genHikariCalc();
  return genTableProblem(HIKARI_DATA, level);
}

