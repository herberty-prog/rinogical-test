/* ----- 文字式 v1：式の値（代入）。答えはすべて整数 ----- */
/* 超基本：x に数を代入して値を求める問題を無限生成（1次・係数は正） */
function genKihon_moji(level) {
  const vars = ["x", "a", "y"];
  const vname = vars[rint(0, vars.length - 1)];
  const k = rint(1, Math.min(3 + level, 6)); // 係数（正）
  const b = rint(-9, 9);                       // 定数
  const v = rint(-6, 6);                        // 代入する値
  const coef = (k === 1) ? vname : `${k}${vname}`;
  const cons = (b === 0) ? "" : (b > 0 ? ` + ${b}` : ` - ${-b}`);
  return { q: `${vname} = ${v} のとき　${coef}${cons} の値`, a: k * v + b, kind: "超基本" };
}

