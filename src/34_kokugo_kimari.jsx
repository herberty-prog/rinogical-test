/* Lv1-2 は基本（adv なし）だけ、Lv3 以降は発展（敬語・品詞の一部など）も混ぜる */
function genKimariProblem(level) {
  const pool = level >= 3 ? KIMARI_DATA : KIMARI_DATA.filter(d => !d.adv);
  const d = pool[rint(0, pool.length - 1)];
  return { type: "text", ui: "choice", kind: d.kind, q: d.q, a: d.a, choices: shuffle([d.a].concat(d.ng)), why: d.why };
}

