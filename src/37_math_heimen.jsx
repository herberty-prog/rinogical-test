const SECTOR_SET = []; // 弧の長さ・面積がどちらも整数×π になる (r, 中心角) の組
for (const r of [2, 3, 4, 6, 8, 9, 10, 12]) for (const d of [30, 45, 60, 90, 120, 135, 150, 180, 210, 240, 270, 300]) {
  if ((2 * r * d) % 360 === 0 && (r * r * d) % 360 === 0) SECTOR_SET.push([r, d]);
}

function heimenTerm() {
  const d = pickOne(HEIMEN_TERMS);
  return { q: d.q, a: d.a, type: "text", ui: "choice", choices: shuffle([d.a].concat(d.ng)), kind: "用語", why: d.why, text: true };
}

function genKihon_heimen(level) {
  const t = rint(1, 3);
  if (t === 1) { // 円の周の長さ
    const r = rint(1, 12), k = 2 * r;
    return { q: "この円の周の長さは何cm？", a: piStr(k), type: "text", ui: "choice", choices: piChoices(k, [r, r * r, 4 * r]), kind: "超基本", text: true,
      fig: { type: "circle", r }, v: { t: "circ_len", r } };
  }
  if (t === 2) { // 円の面積
    const r = rint(2, 12), k = r * r;
    return { q: "この円の面積は何cm²？", a: piStr(k), type: "text", ui: "choice", choices: piChoices(k, [2 * r, 4 * r, 2 * r * r]), kind: "超基本", text: true,
      fig: { type: "circle", r }, v: { t: "circ_area", r } };
  }
  return heimenTerm();
}

function genStd_heimen(level) {
  const t = rint(1, 4);
  const [r, d] = pickOne(SECTOR_SET);
  if (t === 1) { // おうぎ形の弧の長さ
    const k = 2 * r * d / 360;
    return { q: "このおうぎ形の弧の長さは何cm？", a: piStr(k), type: "text", ui: "choice", choices: piChoices(k, [2 * r, r * r * d / 360, k * 2, k + 1]), kind: "標準", text: true,
      fig: { type: "sector", r, deg: d }, v: { t: "arc", r, deg: d } };
  }
  if (t === 2) { // おうぎ形の面積
    const k = r * r * d / 360;
    return { q: "このおうぎ形の面積は何cm²？", a: piStr(k), type: "text", ui: "choice", choices: piChoices(k, [r * r, 2 * r * d / 360, k * 2, k + 2]), kind: "標準", text: true,
      fig: { type: "sector", r, deg: d }, v: { t: "sector", r, deg: d } };
  }
  if (t === 3) { // 弧の長さから中心角
    const k = 2 * r * d / 360;
    return { q: `半径${r}cm、弧の長さ${piStr(k)}cmのおうぎ形の中心角は何度？`, a: d, kind: "標準", text: true,
      choices: choices4(d, [d / 2, 360 - d, d + 30, d * 2].filter(x => x > 0 && x < 360 && Number.isInteger(x))), ui: "choice", v: { t: "deg_from_arc", r, k } };
  }
  return heimenTerm();
}

