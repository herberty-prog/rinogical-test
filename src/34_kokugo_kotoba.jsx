/* Lv1-2 は対義語・類義語、Lv3 以降は四字熟語も混ぜる */
function genGoiProblem(level) {
  const pool = level >= 3 ? GOI_DATA : GOI_DATA.filter(d => d.kind !== "四字熟語");
  const d = pool[rint(0, pool.length - 1)];
  const q = d.kind === "対義語" ? `「${d.w}」の対義語（反対の意味のことば）はどれ？`
    : d.kind === "類義語" ? `「${d.w}」の類義語（にた意味のことば）はどれ？`
    : `四字熟語「${d.w}」の□に入る漢字はどれ？`;
  return { type: "text", ui: "choice", kind: d.kind, q, a: d.a, choices: shuffle([d.a].concat(d.ng)), mark: d.w, why: d.why };
}

