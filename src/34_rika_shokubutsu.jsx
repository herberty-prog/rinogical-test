/* レベルで出題範囲を変える：Lv1-2=基本のみ / Lv3+=発展も混ざる */
function genRikaProblem(level) {
  const pool = level >= 3 ? RIKA_DATA : RIKA_DATA.filter(d => !d.adv);
  const d = pool[rint(0, pool.length - 1)];
  return { type: "text", ui: "choice", kind: d.adv ? "発展" : "基本", q: d.q, a: d.a, choices: shuffle([d.a].concat(d.ng)), why: d.why };
}

